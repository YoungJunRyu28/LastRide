#!/usr/bin/env python3
"""
Builds lib/stationNamesData.ts: Japanese ⇄ English railway station names for
lib/stationNames.ts, from OpenStreetMap (© OpenStreetMap contributors, ODbL).

Usage: python3 scripts/build-station-names.py chunk0.json chunk1.json ...
Each file is an Overpass API JSON answer for nodes tagged railway=station
(or halt) with name and name:en, e.g. one per region of Japan:

  [out:json][timeout:120];
  (node["railway"="station"]["name"]["name:en"](S,W,N,E);
   node["railway"="halt"]["name"]["name:en"](S,W,N,E););
  out tags;
"""
import collections
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "lib" / "stationNamesData.ts"
JAPANESE = re.compile(r"[぀-ヿ㐀-鿿]")


def clean_ja(name: str) -> str:
    name = re.sub(r"[（(][^）)]*[）)]", "", name).strip()
    return re.sub(r"駅$", "", name).strip()


def clean_en(name: str) -> str:
    name = re.sub(r"\s*\([^)]*\)", "", name).strip()
    name = re.sub(r"\s+(Station|Sta\.)$", "", name, flags=re.I).strip()
    return re.sub(r"\s+", " ", name)


def main(paths):
    counts = collections.defaultdict(collections.Counter)
    for path in paths:
        for element in json.load(open(path))["elements"]:
            tags = element.get("tags", {})
            ja, en = clean_ja(tags.get("name", "")), clean_en(tags.get("name:en", ""))
            # Only real pairs: a Japanese name and a different, Latin-script English one.
            if not ja or not en or not JAPANESE.search(ja) or JAPANESE.search(en) or "\t" in ja + en:
                continue
            counts[ja][en] += 1
    # The most common English name for each Japanese one.
    pairs = sorted((ja, names.most_common(1)[0][0]) for ja, names in counts.items())
    body = "\n".join(f"{ja}\t{en}" for ja, en in pairs)
    OUT.write_text(
        "/**\n"
        " * Generated by scripts/build-station-names.py — do not edit by hand.\n"
        " * Railway station names in Japan, Japanese<TAB>English, one per line.\n"
        " * © OpenStreetMap contributors, ODbL (https://www.openstreetmap.org/copyright).\n"
        " */\n"
        f"export const STATION_NAMES = {json.dumps(body, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"{len(pairs)} stations -> {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main(sys.argv[1:])
