#!/usr/bin/env python3
"""
Builds lib/stationPointsData.ts: every passenger railway station in Japan,
Japanese name and position, for lib/stationIndex.ts (is this place a real
station?). From 国土数値情報（鉄道データ）N02, 国土交通省, CC BY 4.0.

Usage:
  1. Download N02-<year>_GML.zip from
     https://nlftp.mlit.go.jp/ksj/gml/datalist/KsjTmplt-N02-<year>.html
  2. python3 scripts/build-station-points.py <unzipped>/UTF-8/N02-<yy>_Station.geojson <yy>
     (<yy> = the edition's two digits, e.g. 25 for N02-25, data as of 2025-12-31)

.github/workflows/station-list.yml runs this monthly and opens a pull request
when a newer edition is out.

Left out: cable cars (鉄道区分 13 鋼索鉄道), trolleybuses (17) and the
guideway bus (名古屋ガイドウェイバス): a route "from" those isn't a train.
Freight-only terminals and closed lines aren't in N02 at all.
"""
import json
import math
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "lib" / "stationPointsData.ts"
NOT_TRAINS_CLASSES = {"13", "17"}
NOT_TRAINS_OPERATORS = {"名古屋ガイドウェイバス"}
# Platforms of one station on several lines: one point per name within this.
SAME_STATION_METERS = 600


def normalize(name: str) -> str:
    """Must match normalizeStationName in lib/stationIndex.ts."""
    name = re.sub(r"[〈<＜（(［\[][^〉>＞）)］\]]*[〉>＞）)］\]]", "", name)
    name = re.sub(r"\s+", "", name).replace("ヶ", "ケ").replace("ヵ", "カ")
    name = re.sub(r"^JR", "", name)
    return re.sub(r"駅$", "", name)


def meters(a, b):
    dy = (a[0] - b[0]) * 111_320
    dx = (a[1] - b[1]) * 111_320 * math.cos(math.radians(a[0]))
    return math.hypot(dx, dy)


def main(path: str, year: str):
    features = json.load(open(path, encoding="utf-8"))["features"]
    points: dict[str, list[list[float]]] = {}
    kept = 0
    for feature in features:
        props = feature["properties"]
        if props["N02_001"] in NOT_TRAINS_CLASSES or props["N02_004"] in NOT_TRAINS_OPERATORS:
            continue
        name = normalize(props["N02_005"])
        if not name:
            continue
        coords = feature["geometry"]["coordinates"]
        lat = sum(c[1] for c in coords) / len(coords)
        lon = sum(c[0] for c in coords) / len(coords)
        kept += 1
        same = points.setdefault(name, [])
        for point in same:
            if meters(point, (lat, lon)) <= SAME_STATION_METERS:
                break
        else:
            same.append([lat, lon])
    lines = sorted(
        f"{name}\t{lat:.4f}\t{lon:.4f}" for name, spots in points.items() for lat, lon in spots
    )
    OUT.write_text(
        "/**\n"
        " * Generated by scripts/build-station-points.py — do not edit by hand.\n"
        " * Passenger railway stations in Japan: Japanese name<TAB>latitude<TAB>longitude, one per line.\n"
        f" * 出典：国土数値情報（鉄道データ）N02-{year}（国土交通省）を加工して作成, CC BY 4.0.\n"
        " */\n"
        f"export const STATION_POINTS_YEAR = \"20{year}\";\n"
        f"export const STATION_POINTS = {json.dumps(chr(10).join(lines), ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"{kept} station entries -> {len(lines)} points ({len(points)} names) -> {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
