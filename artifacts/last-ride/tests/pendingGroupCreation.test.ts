import { beforeEach, describe, expect, test, vi } from "vitest";

const { storage, failures, cryptoRandom } = vi.hoisted(() => ({
  storage: new Map<string, string>(),
  failures: { write: false },
  cryptoRandom: vi.fn(async (_size: number) => Uint8Array.from(Array.from({ length: 32 }, (_, i) => i))),
}));
vi.mock("expo-crypto", () => ({ getRandomBytesAsync: cryptoRandom }));
vi.mock("@react-native-async-storage/async-storage", () => ({
  default: {
    getItem: vi.fn(async (key: string) => storage.get(key) ?? null),
    setItem: vi.fn(async (key: string, value: string) => {
      if (failures.write) { failures.write = false; throw new Error("disk full"); }
      storage.set(key, value);
    }),
    removeItem: vi.fn(async (key: string) => { storage.delete(key); }),
  },
}));

import { finishGroupCreation, prepareGroupCreation, readPendingGroupCreation, creationDefinitelyRejected } from "@/lib/pendingGroupCreation";

beforeEach(async () => {
  const pending = await readPendingGroupCreation();
  if (pending) await finishGroupCreation(pending.creationKey);
  storage.clear(); failures.write = false; cryptoRandom.mockClear();
});

describe("recoverable group creation before network IO", () => {
  test("abandon only definitive server 400/402 rejections, never timeouts", () => {
    expect([400, 401, 402, 403].map(creationDefinitelyRejected)).toEqual([true, true, true, true]);
    expect([undefined, 0, 500, 503, 409].map(creationDefinitelyRejected)).toEqual([false, false, false, false, false]);
  });
  test("persists 32 cryptographically generated bytes; retries keep the same host token", async () => {
    const created = await prepareGroupCreation("Friends", "Alice", "en");
    expect(created.creationKey).toBe("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f");
    expect(storage.has("lastride-pending-group-creation")).toBe(true);
    expect(await readPendingGroupCreation()).toEqual(created);
    expect((await prepareGroupCreation("Friends", "Alice", "en")).creationKey).toBe(created.creationKey);
    expect(cryptoRandom).toHaveBeenCalledTimes(1);
  });
  test("parallel creates for the same group use one idempotency key", async () => {
    const pending = await Promise.all(Array.from({ length: 20 }, () => prepareGroupCreation("Friends", "Alice", "ja")));
    expect(new Set(pending.map((entry) => entry.creationKey)).size).toBe(1);
    expect(cryptoRandom).toHaveBeenCalledTimes(1);
  });
  test("a different group cannot overwrite an unresolved creation", async () => {
    const original = await prepareGroupCreation("Friends", "Alice", "ja");
    await expect(prepareGroupCreation("Other", "Bob", "ja")).rejects.toThrow("PENDING_GROUP_CREATION");
    expect(await readPendingGroupCreation()).toEqual(original);
  });
  test("a failed local write never starts an unsafe fresh remote operation", async () => {
    failures.write = true;
    await expect(prepareGroupCreation("Friends", "Alice", "ja")).rejects.toThrow("disk full");
    expect(await readPendingGroupCreation()).toBeNull();
  });
  test("completion only removes matching operation and preserves unrelated pending credentials", async () => {
    const pending = await prepareGroupCreation("Friends", "Alice", "ja");
    await finishGroupCreation("unrelated");
    expect(await readPendingGroupCreation()).toEqual(pending);
    await finishGroupCreation(pending.creationKey);
    expect(await readPendingGroupCreation()).toBeNull();
  });
});
